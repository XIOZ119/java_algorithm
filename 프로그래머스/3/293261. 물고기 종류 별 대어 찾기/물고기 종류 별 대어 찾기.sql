SELECT B.ID, A.FISH_NAME, A.LENGTH
FROM (
    SELECT F.FISH_TYPE, N.FISH_NAME AS FISH_NAME, MAX(F.LENGTH) AS LENGTH
    FROM FISH_INFO F
    JOIN FISH_NAME_INFO N
        ON F.FISH_TYPE = N.FISH_TYPE
    GROUP BY F.FISH_TYPE
) AS A
JOIN FISH_INFO B
    ON A.FISH_TYPE = B.FISH_TYPE 
    AND A.LENGTH = B.LENGTH
ORDER BY B.ID ASC;